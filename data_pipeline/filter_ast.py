#!/usr/bin/env python3
"""
open-moe-48b High-Throughput Code Quality & AST Filter
=====================================================
Multi-process filtering engine for petabyte-scale code corpora.
Rejects:
  - Files failing Python AST syntax checks.
  - Minified / obfuscated source code (avg line length > 1000 or max line length > 10000).
  - Lockfiles, auto-generated stubs, protobufs, vendored modules.
  - Low-entropy or binary files (alphanumeric character ratio < 0.65).
  - Trivial files (< 5 lines) or monolithic machine dumps (> 20,000 lines).
  - Pathological comment-to-code ratios (> 90% comments or < 1% code).
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import logging
import os
import re
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Dict, Generator, List, Optional, Set, Tuple

try:
    from tqdm import tqdm
except ImportError:
    # Minimal fallback progress tracker if tqdm is not yet installed
    def tqdm(iterable, **kwargs):
        return iterable

logging.basicConfig(
    level=logging.INFO,
    format="[%(asctime)s] [%(levelname)s] %(name)s: %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)
logger = logging.getLogger("filter_ast")

SUPPORTED_EXTENSIONS: dict[str, str] = {
    ".py": "python",
    ".rs": "rust",
    ".c": "c",
    ".h": "c",
    ".cpp": "cpp",
    ".hpp": "cpp",
    ".cc": "cpp",
    ".go": "go",
    ".js": "javascript",
    ".ts": "typescript",
    ".java": "java",
}

EXCLUDED_FILENAMES: set[str] = {
    "package-lock.json",
    "cargo.lock",
    "yarn.lock",
    "poetry.lock",
    "pnpm-lock.yaml",
    "composer.lock",
    "go.sum",
    "gemfile.lock",
}

GENERATED_FILE_PATTERNS: list[re.Pattern] = [
    re.compile(r".*_pb2(_grpc)?\.py$", re.IGNORECASE),
    re.compile(r".*\.pb\.go$", re.IGNORECASE),
    re.compile(r".*\.min\.(js|css)$", re.IGNORECASE),
    re.compile(r".*\.generated\..*$", re.IGNORECASE),
    re.compile(r".*\.d\.ts$", re.IGNORECASE),
]

AUTO_GEN_HEADER_MARKERS: list[str] = [
    "do not edit",
    "autogenerated",
    "auto-generated",
    "generated by",
    "code generated by",
    "this file is generated",
]


@dataclass
class FilterResult:
    path: str
    language: str
    is_valid: bool
    rejection_reason: Optional[str] = None
    line_count: int = 0
    byte_size: int = 0
    alpha_ratio: float = 0.0
    sha256: str = ""


def check_python_ast(source_code: str) -> tuple[bool, Optional[str]]:
    """Strictly validates syntax using the built-in Python Abstract Syntax Tree."""
    try:
        ast.parse(source_code)
        return True, None
    except SyntaxError as e:
        return False, f"SyntaxError at line {e.lineno}: {e.msg}"
    except Exception as e:
        return False, f"AST Parse Error: {str(e)}"


def compute_alpha_ratio(text: str, ignore_whitespace: bool = True) -> float:
    """Computes the ratio of alphanumeric characters.
    By default, calculates over non-whitespace characters (standard in BigCode / The Stack)
    so clean, indented code is not falsely rejected.
    """
    if ignore_whitespace:
        non_ws_chars = [c for c in text if not c.isspace()]
        if not non_ws_chars:
            return 0.0
        return sum(1 for c in non_ws_chars if c.isalnum()) / len(non_ws_chars)
    else:
        if not text:
            return 0.0
        return sum(1 for c in text if c.isalnum()) / len(text)



def analyze_code_structure(lines: list[str], language: str) -> tuple[int, int]:
    """Calculates code lines and comment lines using language-aware heuristics."""
    comment_lines = 0
    code_lines = 0

    comment_prefixes: dict[str, tuple[str, ...]] = {
        "python": ("#",),
        "rust": ("//", "/*", "*"),
        "c": ("//", "/*", "*"),
        "cpp": ("//", "/*", "*"),
        "go": ("//", "/*", "*"),
        "javascript": ("//", "/*", "*"),
        "typescript": ("//", "/*", "*"),
        "java": ("//", "/*", "*"),
    }
    prefixes = comment_prefixes.get(language, ("#", "//"))

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        if any(stripped.startswith(p) for p in prefixes):
            comment_lines += 1
        else:
            code_lines += 1

    return code_lines, comment_lines


def evaluate_file(file_path_str: str) -> FilterResult:
    """Evaluates a single code file against all quality and syntax gates."""
    path = Path(file_path_str)
    filename_lower = path.name.lower()
    ext = path.suffix.lower()

    language = SUPPORTED_EXTENSIONS.get(ext, "unknown")

    # Gate 1: Check known lockfiles
    if filename_lower in EXCLUDED_FILENAMES:
        return FilterResult(
            path=file_path_str,
            language=language,
            is_valid=False,
            rejection_reason="excluded_lockfile",
        )

    # Gate 2: Check generated file regexes
    for pattern in GENERATED_FILE_PATTERNS:
        if pattern.match(filename_lower):
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="generated_file_pattern",
            )

    try:
        content_bytes = path.read_bytes()
        byte_size = len(content_bytes)

        if byte_size == 0:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="empty_file",
                byte_size=0,
            )

        # Gate 3: Reject non-UTF-8 or binary files
        try:
            content_text = content_bytes.decode("utf-8")
        except UnicodeDecodeError:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="unicode_decode_error",
                byte_size=byte_size,
            )

        sha256_hash = hashlib.sha256(content_bytes).hexdigest()
        lines = content_text.splitlines()
        line_count = len(lines)

        # Gate 4: Line count boundaries (5 < lines < 20,000)
        if line_count <= 5:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="too_few_lines",
                line_count=line_count,
                byte_size=byte_size,
                sha256=sha256_hash,
            )

        if line_count >= 20000:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="too_many_lines",
                line_count=line_count,
                byte_size=byte_size,
                sha256=sha256_hash,
            )

        # Gate 5: Minified code detection (avg line length > 1000 or max line length > 10000)
        avg_line_len = byte_size / max(line_count, 1)
        max_line_len = max(len(line) for line in lines)
        if avg_line_len > 1000 or max_line_len > 10000:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="minified_code",
                line_count=line_count,
                byte_size=byte_size,
                sha256=sha256_hash,
            )

        # Gate 6: Alphanumeric character density (reject if < 0.65)
        alpha_ratio = compute_alpha_ratio(content_text)
        if alpha_ratio < 0.65:
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason=f"low_alpha_ratio_{alpha_ratio:.3f}",
                line_count=line_count,
                byte_size=byte_size,
                alpha_ratio=alpha_ratio,
                sha256=sha256_hash,
            )

        # Gate 7: Auto-generated header notice check in the first 20 lines
        header_sample = "\n".join(lines[:20]).lower()
        if any(marker in header_sample for marker in AUTO_GEN_HEADER_MARKERS):
            return FilterResult(
                path=file_path_str,
                language=language,
                is_valid=False,
                rejection_reason="autogenerated_header_marker",
                line_count=line_count,
                byte_size=byte_size,
                sha256=sha256_hash,
            )

        # Gate 8: Comment-to-code ratio
        code_lines, comment_lines = analyze_code_structure(lines, language)
        total_content_lines = code_lines + comment_lines
        if total_content_lines > 0:
            comment_ratio = comment_lines / total_content_lines
            if comment_ratio > 0.90:
                return FilterResult(
                    path=file_path_str,
                    language=language,
                    is_valid=False,
                    rejection_reason=f"excessive_comments_{comment_ratio:.2f}",
                    line_count=line_count,
                    byte_size=byte_size,
                    sha256=sha256_hash,
                )

        # Gate 9: Language-specific AST syntax validation
        if language == "python":
            ast_valid, ast_err = check_python_ast(content_text)
            if not ast_valid:
                return FilterResult(
                    path=file_path_str,
                    language=language,
                    is_valid=False,
                    rejection_reason=f"python_ast_error: {ast_err}",
                    line_count=line_count,
                    byte_size=byte_size,
                    alpha_ratio=alpha_ratio,
                    sha256=sha256_hash,
                )

        # Passed all filters
        return FilterResult(
            path=file_path_str,
            language=language,
            is_valid=True,
            line_count=line_count,
            byte_size=byte_size,
            alpha_ratio=alpha_ratio,
            sha256=sha256_hash,
        )

    except Exception as e:
        return FilterResult(
            path=file_path_str,
            language=language,
            is_valid=False,
            rejection_reason=f"unhandled_read_error: {str(e)}",
        )


def batch_iterator(items: list[str], batch_size: int) -> Generator[list[str], None, None]:
    for i in range(0, len(items), batch_size):
        yield items[i : i + batch_size]


def process_directory(
    input_dir: Path,
    output_manifest: Path,
    workers: int = 8,
    batch_size: int = 500,
) -> tuple[int, int]:
    """Recurses through input_dir and evaluates all supported source files in parallel."""
    logger.info("Discovering source files in %s...", input_dir)
    candidate_paths: list[str] = []
    for root, _, files in os.walk(input_dir):
        for f in files:
            p = Path(root) / f
            if p.suffix.lower() in SUPPORTED_EXTENSIONS or f.lower() in EXCLUDED_FILENAMES:
                candidate_paths.append(str(p))

    logger.info("Discovered %d candidate files to evaluate.", len(candidate_paths))
    output_manifest.parent.mkdir(parents=True, exist_ok=True)

    passed_count = 0
    rejected_count = 0
    rejection_stats: dict[str, int] = {}

    with open(output_manifest, "w", encoding="utf-8") as out_f, ProcessPoolExecutor(
        max_workers=workers
    ) as executor:
        for batch in batch_iterator(candidate_paths, batch_size):
            futures = [executor.submit(evaluate_file, f_str) for f_str in batch]
            for future in as_completed(futures):
                result = future.result()
                out_f.write(json.dumps(asdict(result)) + "\n")
                if result.is_valid:
                    passed_count += 1
                else:
                    rejected_count += 1
                    reason = (result.rejection_reason or "unknown").split(":")[0]
                    rejection_stats[reason] = rejection_stats.get(reason, 0) + 1

    logger.info("=== AST & Quality Filter Execution Summary ===")
    logger.info("  Total Processed: %d", passed_count + rejected_count)
    logger.info("  Accepted Files:  %d (%.2f%%)", passed_count, 100.0 * passed_count / max(len(candidate_paths), 1))
    logger.info("  Rejected Files:  %d (%.2f%%)", rejected_count, 100.0 * rejected_count / max(len(candidate_paths), 1))
    logger.info("  Rejection Breakdown:")
    for reason, cnt in sorted(rejection_stats.items(), key=lambda x: -x[1]):
        logger.info("    - %-32s: %d", reason, cnt)
    logger.info("Manifest written to: %s", output_manifest)

    return passed_count, rejected_count


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="High-Throughput AST and Code Quality Filter for open-moe-48b."
    )
    parser.add_argument(
        "--input-dir",
        type=Path,
        required=True,
        help="Root directory containing raw code repositories.",
    )
    parser.add_argument(
        "--output-manifest",
        type=Path,
        default=Path("data_pipeline_output/filtered_manifest.jsonl"),
        help="Target output JSONL path for file evaluation metadata.",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=min(os.cpu_count() or 4, 16),
        help="Number of concurrent worker processes.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=500,
        help="Batch size for process pool dispatch.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not args.input_dir.exists():
        logger.error("Input directory %s does not exist.", args.input_dir)
        sys.exit(1)

    process_directory(
        input_dir=args.input_dir,
        output_manifest=args.output_manifest,
        workers=args.workers,
        batch_size=args.batch_size,
    )


if __name__ == "__main__":
    main()
